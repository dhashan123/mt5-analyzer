"""Build step: inject the public payment addresses into the static site.

The addresses are public by definition - they are printed on the site.  The
private key never leaves ``.secrets/wallet.json``, which is not part of the
site and not part of the repository.

    python build.py --wallet ../../.secrets/wallet.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PUBLIC = HERE / "public"

TEMPLATE = """/* Generated by build.py - do not edit. */
window.MTB5_ORDER = {
  tron: __TRON__,
  eth: __ETH__,
  btc: __BTC__
};
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--wallet", default=str(HERE.parent.parent / ".secrets" / "wallet.json"))
    args = ap.parse_args()

    wallet = json.loads(Path(args.wallet).read_text(encoding="utf-8"))
    addresses = wallet["addresses"]

    body = (TEMPLATE
            .replace("__TRON__", json.dumps(addresses["tron_usdt_trc20"]))
            .replace("__ETH__", json.dumps(addresses["ethereum_usdc_eth"]))
            .replace("__BTC__", json.dumps(addresses["bitcoin"])))
    out = PUBLIC / "config.js"
    out.write_text(body, encoding="utf-8")
    print(f"wrote {out}")
    for name, addr in addresses.items():
        print(f"  {name:24s} {addr}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
